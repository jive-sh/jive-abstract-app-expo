import { Option } from "effect";
import type { AppExpoConfig } from "../public/manifest";

/**
 * Universal links (iOS) and App Links (Android) for the app's domain, configured without the app's own
 * Expo config naming them. `build` writes `GENERATED_APP_CONFIG_FILE` beside the app's app.json; Expo evaluates
 * it with app.json's contents as `config` (https://docs.expo.dev/workflow/configuration/),
 * so `expo config`, `eas update` and the `expo prebuild` EAS Build runs on its own servers all see the result.
 * EAS Build uploads every file git does not ignore, which is why the file must stay out of `.gitignore`.
 */

/** `.cjs`, so Expo loads it as CommonJS whatever the app's package.json `type` says. */
export const GENERATED_APP_CONFIG_FILE = "app.config.cjs";

/** The first line of every generated config, which tells it apart from an app's own `app.config.cjs`. */
export const GENERATED_APP_CONFIG_MARKER = "// @generated by jive-abstract-app-expo";

/** Every name Expo looks for a dynamic config under; it reads only the first one it finds. */
export const DYNAMIC_APP_CONFIG_FILES = [".ts", ".mts", ".cts", ".mjs", ".cjs", ".js"].map((extension) => `app.config${extension}`);

/**
 * Entries appended to the app's own `expo.ios` and `expo.android` arrays, one key per platform that is built.
 * The intent filter is the one Expo documents for App Links, matching every path on the domain
 * (https://docs.expo.dev/linking/android-app-links/).
 */
export interface NativeLinkingConfig {
  readonly ios?: { readonly associatedDomains: ReadonlyArray<string> };
  readonly android?: { readonly intentFilters: ReadonlyArray<unknown> };
}

/** The native linking config for the domain, or None when there is no domain or no native app to link. */
export function nativeLinkingConfig(config: AppExpoConfig): Option.Option<NativeLinkingConfig> {
  const { platforms } = config.native;
  if (platforms.length === 0) return Option.none();
  return Option.map(config.domain, (domain) => ({
    ...(platforms.includes("ios") ? { ios: { associatedDomains: [`applinks:${domain}`] } } : {}),
    ...(platforms.includes("android")
      ? {
        android: {
          intentFilters: [{
            action: "VIEW",
            autoVerify: true,
            data: [{ scheme: "https", host: domain }],
            category: ["BROWSABLE", "DEFAULT"],
          }],
        },
      }
      : {}),
  }));
}

/**
 * The source of `GENERATED_APP_CONFIG_FILE`. It is self-contained so the EAS Build server can evaluate it
 * without this package, and it appends only entries the app's config lacks, so the app keeps any of its own.
 */
export function renderAppConfig(linking: NativeLinkingConfig): string {
  return `${GENERATED_APP_CONFIG_MARKER} from jive["app-expo"] in package.json, on every build.
// Expo reads it over app.json. Keep it out of .gitignore, since EAS Build uploads only files git does not
// ignore, and out of commits, since the next build rewrites it.
const additions = ${JSON.stringify(linking, null, 2)};

module.exports = ({ config }) => {
  const result = { ...config };
  for (const [platform, fields] of Object.entries(additions)) {
    const section = { ...(result[platform] ?? {}) };
    for (const [field, items] of Object.entries(fields)) {
      const existing = section[field] ?? [];
      const present = new Set(existing.map((item) => JSON.stringify(item)));
      section[field] = [...existing, ...items.filter((item) => !present.has(JSON.stringify(item)))];
    }
    result[platform] = section;
  }
  return result;
};
`;
}
